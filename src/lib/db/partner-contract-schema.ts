import { customType, integer, jsonb, pgTable, text, timestamp } from "drizzle-orm/pg-core";
import type {
  ContractIdentity,
  ContractSnapshot,
  CommercialSchedule,
  ProviderSnapshot,
} from "@/lib/partners/contracts/domain";
const date = (name: string) => timestamp(name, { withTimezone: true });
const bytes = customType<{ data: Buffer; driverData: Buffer }>({ dataType: () => "bytea" });
export const partnerContractTemplates = pgTable("PartnerContractTemplate", {
  id: text("id").primaryKey(),
  agreementType: text("agreementType").notNull(),
  version: text("version").notNull(),
  title: text("title").notNull(),
  body: text("body").notNull(),
  checksum: text("checksum").notNull(),
  approvedBy: text("approvedBy"),
  approvedAt: date("approvedAt"),
  legalReviewReference: text("legalReviewReference"),
  revokedAt: date("revokedAt"),
  createdAt: date("createdAt").defaultNow().notNull(),
});
export const partnerContractProfiles = pgTable("PartnerContractProfile", {
  id: text("id").primaryKey(),
  applicationId: text("applicationId").notNull(),
  version: integer("version").notNull(),
  identity: jsonb("identity").$type<ContractIdentity>().notNull(),
  checksum: text("checksum").notNull(),
  consentVersion: text("consentVersion").notNull(),
  consentAt: date("consentAt").notNull(),
  submittedBy: text("submittedBy").notNull(),
  reviewedBy: text("reviewedBy"),
  reviewedAt: date("reviewedAt"),
  reviewEvidence: text("reviewEvidence"),
  createdAt: date("createdAt").defaultNow().notNull(),
});
