export const partnerContracts = pgTable("PartnerContract", {
  id: text("id").primaryKey(),
  applicationId: text("applicationId").notNull(),
  partnerId: text("partnerId").notNull(),
  revision: integer("revision").notNull(),
  agreementType: text("agreementType").notNull(),
  templateId: text("templateId").notNull(),
  templateVersion: text("templateVersion").notNull(),
  profileId: text("profileId").notNull(),
  scheduleId: text("scheduleId").notNull(),
  commercialTermsVersion: text("commercialTermsVersion").notNull(),
  snapshot: jsonb("snapshot").$type<ContractSnapshot>().notNull(),
  mode: text("mode").notNull(),
  status: text("status").notNull().default("pending"),
  provider: text("provider").notNull(),
  providerReference: text("providerReference"),
  sourceArtifactId: text("sourceArtifactId"),
  documentChecksum: text("documentChecksum"),
  signedArtifactId: text("signedArtifactId"),
  signedDocumentChecksum: text("signedDocumentChecksum"),
  auditArtifactId: text("auditArtifactId"),
  auditEvidenceChecksum: text("auditEvidenceChecksum"),
  providerSnapshot: jsonb("providerSnapshot").$type<ProviderSnapshot>(),
  partnerSignedAt: date("partnerSignedAt"),
  companySignedAt: date("companySignedAt"),
  verifiedAt: date("verifiedAt"),
  executedAt: date("executedAt"),
  expiresAt: date("expiresAt").notNull(),
  lastErrorCode: text("lastErrorCode"),
  createdAt: date("createdAt").defaultNow().notNull(),
  updatedAt: date("updatedAt").defaultNow().notNull(),
});
